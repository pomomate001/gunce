"""Generates lib/core/icons.dart: Phosphor icons (MIT) used by the app, as plain IconData.

The phosphor_flutter package no longer compiles (IconData became a final class), so the
icon fonts are vendored in assets/fonts and only the icons referenced in lib/ are declared.

    python tool/gen_icons.py <path to phosphor_flutter-2.1.0 package>

Add a new icon by using Ph.<name> / PhFill.<name> / PhBold.<name> in code and re-running.
"""
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STYLES = {"Ph": ("regular", "PhosphorRegular", "Phosphor.ttf"),
          "PhFill": ("fill", "PhosphorFill", "Phosphor-Fill.ttf"),
          "PhBold": ("bold", "PhosphorBold", "Phosphor-Bold.ttf")}


def main() -> None:
    pkg = Path(sys.argv[1])
    code = "\n".join(p.read_text(encoding="utf-8") for p in (ROOT / "lib").rglob("*.dart") if p.name != "icons.dart")
    out = ["// GENERATED by tool/gen_icons.py from Phosphor Icons (MIT, phosphoricons.com). Do not edit.",
           "import 'package:flutter/widgets.dart';", ""]
    for cls, (style, family, font) in STYLES.items():
        used = sorted(set(re.findall(rf"\b{cls}\.([a-zA-Z0-9]+)", code)))
        src = (pkg / "lib" / "src" / f"phosphor_icons_{style}.dart").read_text(encoding="utf-8")
        table = dict(re.findall(r"static const (\w+) = Phosphor\w+IconData\((0x[0-9a-f]+)", src))
        out.append(f"abstract final class {cls} {{")
        for name in used:
            if name not in table:
                raise SystemExit(f"unknown icon {cls}.{name}")
            out.append(f"  static const {name} = IconData({table[name]}, fontFamily: '{family}', matchTextDirection: true);")
        out.append("}\n")
        shutil.copyfile(pkg / "lib" / "fonts" / font, ROOT / "assets" / "fonts" / f"{family}.ttf")
        print(f"{cls}: {len(used)} icons")
    (ROOT / "lib" / "core" / "icons.dart").write_text("\n".join(out), encoding="utf-8")


if __name__ == "__main__":
    main()
